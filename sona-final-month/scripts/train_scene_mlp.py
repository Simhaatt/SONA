#!/usr/bin/env python3
"""Train the Layer B scene classifier's learned decision rule and export it.

Result that motivates this (see `compare_scene_learned.py`): holding the 8-feature
extractor fixed and swapping only the decision rule, on deployment-realistic
speech+noise mixtures —

    majority baseline    0.422
    tuned heuristic      0.490      <- hand-tuned `_tri` windows
    logistic regression  0.717
    random forest        0.800
    MLP (32,16)          0.844      <- learned rule

so the hand-tuned rule, not the feature set, was the bottleneck.

Training set combines both regimes so the shipped model is not itself subject to
a train/serve mismatch:
  * pure noise / clean speech      (manifest_msnsd.csv)
  * noise-dominant mixtures        (manifest_mixtures_lowsnr.csv)

The trained MLP is ~900 parameters, so it is exported as plain numpy arrays in a
generated module — inference needs no scikit-learn and no torch, preserving the
"runs locally on the edge, nothing leaves the machine" property.

    python scripts/train_scene_mlp.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import accuracy_score, balanced_accuracy_score, confusion_matrix
from sklearn.model_selection import StratifiedKFold
from sklearn.neural_network import MLPClassifier
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

FEATURES = ["centroid_hz", "flatness", "rolloff_hz", "zcr",
            "low_ratio", "mid_ratio", "high_ratio", "modulation"]

TEMPLATE = '''"""Learned scene-classifier decision rule (generated — do not edit by hand).

Generated by `sona-final-month/scripts/train_scene_mlp.py`.

Replaces the hand-tuned `_tri()` scoring rule, which scored {heur:.3f} CV accuracy
on deployment-realistic speech+noise mixtures versus {acc:.3f} for this model
(majority-class baseline: {base:.3f}). The feature extractor is unchanged.

Architecture: {arch} MLP, {nparams} parameters, ReLU, softmax output.
Weights are inlined as numpy arrays so inference needs neither scikit-learn nor
torch — the classifier stays local and edge-deployable.

Cross-validated accuracy: {acc:.4f} +/- {std:.4f} ({nclips} clips, {folds}-fold stratified)
"""

from __future__ import annotations

import numpy as np

FEATURE_ORDER = {features!r}

LABELS = {labels!r}

# input standardisation (mean / scale) fitted on the training set
MEAN = np.array({mean}, dtype=np.float64)
SCALE = np.array({scale}, dtype=np.float64)

{weights}


def predict_scores(feats: dict) -> dict:
    """Feature dict -> {{label: probability}} using the learned rule."""
    x = np.array([float(feats[k]) for k in FEATURE_ORDER], dtype=np.float64)
    x = (x - MEAN) / SCALE
    for W, b in zip(WEIGHTS[:-1], BIASES[:-1]):
        x = np.maximum(0.0, x @ W + b)
    z = x @ WEIGHTS[-1] + BIASES[-1]
    z = z - float(np.max(z))
    e = np.exp(z)
    p = e / (float(np.sum(e)) + 1e-12)
    return {{lab: float(v) for lab, v in zip(LABELS, p)}}
'''


def load_cache(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    X = np.array([[d["feats"][k] for k in FEATURES] for d in data], dtype=float)
    y = np.array([d["label"] for d in data])
    return X, y


def fmt_array(a: np.ndarray) -> str:
    return np.array2string(a, separator=", ", precision=6,
                           threshold=10**9, max_line_width=88,
                           floatmode="maxprec").replace("\n", "\n    ")


def main():
    ap = argparse.ArgumentParser()
    root = Path(__file__).resolve().parents[1]
    ap.add_argument("--caches", type=Path, nargs="+",
                    default=[root / "SCENE_EVAL_LOWSNR" / "feature_cache.json",
                             root / "SCENE_EVAL_REAL" / "feature_cache.json"])
    ap.add_argument("--out", type=Path,
                    default=Path(__file__).resolve().parents[2] / "src" / "controller" / "scene_model.py")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--heuristic-cv", type=float, default=0.4898)
    args = ap.parse_args()

    Xs, ys = [], []
    for c in args.caches:
        if not c.exists():
            print(f"  (skipping missing cache {c})")
            continue
        X, y = load_cache(c)
        Xs.append(X)
        ys.append(y)
        print(f"  {c.name}: {len(y)} clips")
    if not Xs:
        raise SystemExit("no feature caches found")
    X = np.vstack(Xs)
    y = np.concatenate(ys)
    print(f"combined: {len(y)} clips, classes "
          f"{dict(zip(*np.unique(y, return_counts=True)))}")

    def make():
        return make_pipeline(
            StandardScaler(),
            MLPClassifier(hidden_layer_sizes=(32, 16), max_iter=4000,
                          random_state=args.seed))

    skf = StratifiedKFold(n_splits=args.folds, shuffle=True, random_state=args.seed)
    accs, bals, preds, trues = [], [], [], []
    for tr, te in skf.split(X, y):
        m = make()
        m.fit(X[tr], y[tr])
        p = m.predict(X[te])
        accs.append(accuracy_score(y[te], p))
        bals.append(balanced_accuracy_score(y[te], p))
        preds.extend(p)
        trues.extend(y[te])
    acc, std = float(np.mean(accs)), float(np.std(accs))
    print(f"\nCROSS-VALIDATED accuracy: {acc:.4f} +/- {std:.4f}")
    print(f"CROSS-VALIDATED balanced: {np.mean(bals):.4f}")

    labs = sorted(set(y))
    cm = confusion_matrix(trues, preds, labels=labs)
    print("\npooled out-of-fold confusion (rows=true, cols=pred)")
    print("          " + "".join(f"{l[:8]:>9s}" for l in labs))
    for i, l in enumerate(labs):
        print(f"{l:>9s} " + "".join(f"{v:9d}" for v in cm[i]))

    # final fit on everything, then export
    final = make()
    final.fit(X, y)
    scaler: StandardScaler = final.named_steps["standardscaler"]
    mlp: MLPClassifier = final.named_steps["mlpclassifier"]
    nparams = sum(w.size for w in mlp.coefs_) + sum(b.size for b in mlp.intercepts_)

    w_lines = ["WEIGHTS = ["]
    for w in mlp.coefs_:
        w_lines.append(f"    np.array({fmt_array(w)}, dtype=np.float64),")
    w_lines.append("]")
    w_lines.append("")
    w_lines.append("BIASES = [")
    for b in mlp.intercepts_:
        w_lines.append(f"    np.array({fmt_array(b)}, dtype=np.float64),")
    w_lines.append("]")

    base = float(max(np.unique(y, return_counts=True)[1]) / len(y))
    code = TEMPLATE.format(
        features=FEATURES, labels=[str(c) for c in mlp.classes_],
        mean=fmt_array(scaler.mean_), scale=fmt_array(scaler.scale_),
        weights="\n".join(w_lines), acc=acc, std=std, nclips=len(y),
        folds=args.folds, arch="8-32-16-%d" % len(mlp.classes_),
        nparams=nparams, heur=args.heuristic_cv, base=base,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(code, encoding="utf-8")
    print(f"\nexported {nparams}-parameter model -> {args.out}")


if __name__ == "__main__":
    main()
