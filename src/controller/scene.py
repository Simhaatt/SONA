"""Lightweight feature-based scene classifier for SONA Layer B."""

from __future__ import annotations

from dataclasses import asdict, dataclass

import numpy as np

from ..utils.audio_io import DEFAULT_SR

try:  # generated by sona-final-month/scripts/train_scene_mlp.py
    from . import scene_model as _LEARNED  # type: ignore
except Exception:  # pragma: no cover - falls back to the hand-tuned rule
    _LEARNED = None  # type: ignore

EPS = 1e-8


@dataclass(frozen=True)
class ScenePrediction:
    """Scene label plus confidence and interpretable audio features."""

    label: str
    confidence: float
    features: dict[str, float]

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


class SceneClassifier:
    """Simple deterministic classifier for speech/music/traffic/fan/crowd/unknown."""

    labels = ("speech", "music", "traffic", "fan", "crowd", "mixed", "unknown")

    #: below this softmax probability the learned rule abstains to "mixed"
    min_confidence = 0.45

    def __init__(self, sr: int = DEFAULT_SR, n_fft: int = 1024, hop: int = 256,
                 use_learned: bool = True) -> None:
        self.sr = sr
        self.n_fft = n_fft
        self.hop = hop
        self.use_learned = use_learned and _LEARNED is not None

    def predict(self, wav: np.ndarray, sr: int | None = None) -> ScenePrediction:
        if sr is not None and sr != self.sr:
            raise ValueError(f"expected {self.sr} Hz audio, got {sr} Hz")
        x = np.asarray(wav, dtype=np.float32)
        if x.ndim > 1:
            x = x.mean(axis=-1)
        feats = self.features(x)

        if feats["rms"] < 1e-4:
            return ScenePrediction(label="unknown", confidence=0.2, features=feats)

        if self.use_learned:
            probs = _LEARNED.predict_scores(feats)
            label, confidence = max(probs.items(), key=lambda item: item[1])
            # the learned rule covers speech/crowd/fan/traffic only; when it is
            # not confident, defer to "mixed" rather than force one of those
            if confidence < self.min_confidence:
                label = "mixed"
            return ScenePrediction(label=label, confidence=float(confidence),
                                   features=feats)

        scores = self._scores(feats)
        label, score = max(scores.items(), key=lambda item: item[1])
        confidence = _soft_confidence(scores, label)
        return ScenePrediction(label=label, confidence=confidence, features=feats)

    def features(self, wav: np.ndarray) -> dict[str, float]:
        x = np.asarray(wav, dtype=np.float32)
        if x.size == 0:
            return _empty_features()
        x = x - float(np.mean(x))
        rms = float(np.sqrt(np.mean(x**2) + EPS))
        frames = _frames(x, self.n_fft, self.hop)
        if frames.size == 0:
            return _empty_features(rms=rms)

        win = np.hanning(self.n_fft).astype(np.float32)
        spec = np.fft.rfft(frames * win[None, :], axis=1)
        mag = np.abs(spec).astype(np.float32) + EPS
        power = mag**2
        freqs = np.fft.rfftfreq(self.n_fft, d=1.0 / self.sr).astype(np.float32)
        total = power.sum(axis=1) + EPS

        centroid = (power * freqs[None, :]).sum(axis=1) / total
        flatness = np.exp(np.mean(np.log(mag), axis=1)) / (np.mean(mag, axis=1) + EPS)
        rolloff = _rolloff(power, freqs, ratio=0.85)
        low = _band_energy(power, freqs, 20.0, 250.0)
        mid = _band_energy(power, freqs, 250.0, 3000.0)
        high = _band_energy(power, freqs, 3000.0, self.sr / 2.0)
        zcr = _zero_crossing_rate(frames)
        frame_rms = np.sqrt(np.mean(frames**2, axis=1) + EPS)

        # ---- shipped base 8 (means over frames) ----
        f = {
            "rms": rms,
            "centroid_hz": float(np.mean(centroid)),
            "flatness": float(np.mean(flatness)),
            "rolloff_hz": float(np.mean(rolloff)),
            "zcr": float(np.mean(zcr)),
            "low_ratio": float(np.mean(low)),
            "mid_ratio": float(np.mean(mid)),
            "high_ratio": float(np.mean(high)),
            "modulation": float(np.std(frame_rms) / (np.mean(frame_rms) + EPS)),
        }

        # ---- rich additions (temporal + finer spectral) ----
        # These capture how the noise evolves over time (steady fan vs bursty
        # babble vs passing traffic) and finer band structure. The learned rule
        # in scene_model.py is trained on this exact set; keep it in sync with
        # sona-final-month/scripts/scene_feature_lib.compute_all.
        for name, series in (("centroid", centroid), ("flatness", flatness),
                             ("rolloff", rolloff), ("zcr", zcr),
                             ("low", low), ("mid", mid), ("high", high)):
            f[f"{name}_std"] = float(np.std(series))
            f[f"{name}_iqr"] = float(np.percentile(series, 75) - np.percentile(series, 25))

        logrms = np.log(frame_rms + EPS)
        f["dyn_range_db"] = float(
            20.0 * (np.percentile(logrms, 95) - np.percentile(logrms, 5)) / np.log(10))
        f["delta_centroid"] = float(np.mean(np.abs(np.diff(centroid))))
        f["delta_flux"] = float(np.mean(np.abs(np.diff(mag, axis=0)))) if mag.shape[0] > 1 else 0.0

        f["sub_ratio"] = float(np.mean(_band_energy(power, freqs, 20.0, 120.0)))
        f["lowmid_ratio"] = float(np.mean(_band_energy(power, freqs, 120.0, 500.0)))
        f["presence_ratio"] = float(np.mean(_band_energy(power, freqs, 2000.0, 4000.0)))
        f["brilliance_ratio"] = float(np.mean(_band_energy(power, freqs, 6000.0, self.sr / 2.0)))

        bandwidth = np.sqrt(
            (power * (freqs[None, :] - centroid[:, None]) ** 2).sum(axis=1) / total)
        f["bandwidth_hz"] = float(np.mean(bandwidth))
        f["crest"] = float(np.mean(mag.max(axis=1) / (mag.mean(axis=1) + EPS)))
        sort_p = np.sort(np.log(power + EPS), axis=1)
        k = max(1, sort_p.shape[1] // 10)
        f["contrast"] = float(np.mean(sort_p[:, -k:].mean(axis=1) - sort_p[:, :k].mean(axis=1)))

        f["mod_p90"] = float(np.percentile(frame_rms, 90) / (np.mean(frame_rms) + EPS))
        f["mod_p10"] = float(np.percentile(frame_rms, 10) / (np.mean(frame_rms) + EPS))
        return f

    def _scores(self, f: dict[str, float]) -> dict[str, float]:
        """Score each scene label.

        Thresholds were re-seated on measured feature distributions from a
        98-clip labelled MS-SNSD set (see `sona-final-month/scripts/
        tune_scene_thresholds.py`). The shipped v1 windows scored 0.469 on that
        set; these score 0.714 +/- 0.025 under stratified 5-fold CV.

        Two v1 assumptions were measurably inverted and are corrected here:
        `crowd` rewarded high_ratio in [0.12, 0.55] but real babble measures
        ~0.03, and `speech` carried a `-0.5 * high` penalty despite real speech
        having the highest HF energy (~0.14) of any class.

        `music` is UNVALIDATED — MS-SNSD contains no music, so these windows are
        carried over unfitted and are a known coverage gap.
        """
        centroid = f["centroid_hz"]
        zcr = f["zcr"]
        low = f["low_ratio"]
        mid = f["mid_ratio"]
        high = f["high_ratio"]
        mod = f["modulation"]
        rolloff = f["rolloff_hz"]

        speech = (
            1.00 * _tri(mid, 0.300, 0.720)
            + 1.30 * _tri(mod, 0.550, 1.300)
            + 1.20 * _tri(centroid, 700.0, 1800.0)
            + 0.60 * _tri(zcr, 0.090, 0.220)
            + 1.20 * _tri(high, 0.060, 0.240)
        )
        music = (
            0.80 * _tri(low, 0.150, 0.550)
            + 0.80 * _tri(rolloff, 1200.0, 4500.0)
            + 0.70 * _tri(mod, 0.150, 0.600)
            + 0.50 * _tri(high, 0.050, 0.300)
        )
        fan = (
            2.45 * _tri(mod, 0.000, 0.420)
            + 1.00 * _tri(low, 0.320, 0.780)
            + 0.90 * _tri(centroid, 200.0, 707.7)
            + 0.70 * _tri(mid, 0.160, 0.480)
        )
        traffic = (
            1.40 * _tri(centroid, 60.0, 330.0)
            + 1.30 * _tri(mid, 0.034, 0.240)
            + 0.90 * _tri(low, 0.350, 0.727)
            + 0.60 * _tri(mod, 0.350, 0.950)
        )
        crowd = (
            1.50 * _tri(mid, 0.560, 0.880)
            + 1.00 * _tri(high, 0.000, 0.049)
            + 1.03 * _tri(mod, 0.320, 0.800)
            + 0.80 * _tri(centroid, 430.0, 900.0)
        )
        # fallback floor: wins only when no specific scene scores above it
        mixed = 0.62
        unknown = 0.1
        return {
            "speech": speech,
            "music": music,
            "traffic": traffic,
            "fan": fan,
            "crowd": crowd,
            "mixed": mixed,
            "unknown": unknown,
        }


def _frames(x: np.ndarray, n_fft: int, hop: int) -> np.ndarray:
    if x.size < n_fft:
        x = np.pad(x, (0, n_fft - x.size))
    n = 1 + (x.size - n_fft) // hop
    if n <= 0:
        return np.empty((0, n_fft), dtype=np.float32)
    shape = (n, n_fft)
    strides = (x.strides[0] * hop, x.strides[0])
    return np.lib.stride_tricks.as_strided(x, shape=shape, strides=strides).copy()


def _rolloff(power: np.ndarray, freqs: np.ndarray, ratio: float) -> np.ndarray:
    cumulative = np.cumsum(power, axis=1)
    target = cumulative[:, -1:] * ratio
    idx = np.argmax(cumulative >= target, axis=1)
    return freqs[idx]


def _band_energy(power: np.ndarray, freqs: np.ndarray, lo: float, hi: float) -> np.ndarray:
    mask = (freqs >= lo) & (freqs < hi)
    total = power.sum(axis=1) + EPS
    return power[:, mask].sum(axis=1) / total


def _zero_crossing_rate(frames: np.ndarray) -> np.ndarray:
    signs = np.signbit(frames)
    return np.mean(signs[:, 1:] != signs[:, :-1], axis=1)


def _tri(x: float, lo: float, hi: float) -> float:
    if hi <= lo:
        return 0.0
    center = (lo + hi) * 0.5
    half = (hi - lo) * 0.5
    return max(0.0, 1.0 - abs(float(x) - center) / half)


def _soft_confidence(scores: dict[str, float], label: str) -> float:
    values = np.array(list(scores.values()), dtype=np.float32)
    values = values - float(values.max())
    probs = np.exp(values)
    probs = probs / (float(probs.sum()) + EPS)
    idx = list(scores).index(label)
    return float(np.clip(probs[idx], 0.0, 1.0))


def _empty_features(rms: float = 0.0) -> dict[str, float]:
    return {
        "rms": float(rms),
        "centroid_hz": 0.0,
        "flatness": 0.0,
        "rolloff_hz": 0.0,
        "zcr": 0.0,
        "low_ratio": 0.0,
        "mid_ratio": 0.0,
        "high_ratio": 0.0,
        "modulation": 0.0,
    }
