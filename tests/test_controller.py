"""Layer B controller and offline post-processing tests."""

import numpy as np

from src.controller import (
    ControllerSettings,
    PreferenceMemory,
    SceneClassifier,
    SonaController,
    apply_post_processing,
)


def test_controller_modes_and_scene_routing():
    controller = SonaController()
    assert "speech" in controller.preset_names()
    assert "aggressive_speech" in controller.preset_names()
    assert controller.mode_for_scene("traffic") == "aggressive_speech"
    assert controller.mode_for_scene("fan") == "aggressive_speech"

    speech = controller.settings(mode="speech")
    aggressive = controller.settings(mode="aggressive_speech")
    music = controller.settings(mode="music")
    assert speech.mask_strength > music.mask_strength
    # mask_strength > 1.0 EXTRAPOLATES past the model's own gain estimate
    # (blended = noisy + strength*(enhanced-noisy)). Measured against real clean
    # references, SI-SDR peaks at ~1.0 and falls monotonically above it -- pushing
    # "aggressive" mode's strength past 1.0 actively loses quality (was 1.25, lost
    # ~1.4 dB SI-SDR on average and went negative on hard clips). "Aggressive"
    # therefore no longer means "extrapolate harder"; it differs from "speech" via
    # a lower safety_floor and steeper EQ/compressor, not mask_strength.
    assert speech.mask_strength <= 1.0 and aggressive.mask_strength <= 1.0
    assert aggressive.safety_floor < speech.safety_floor
    assert speech.compressor_makeup_db <= 0.2
    assert len(speech.eq_gains_db) == 8


def test_no_preset_extrapolates_past_the_model_estimate():
    # regression guard for the mask_strength-overshoot bug: mask_strength > 1.0
    # blends BEYOND what the model predicted and was measured to hurt quality
    # monotonically (see test_controller_modes_and_scene_routing). No shipped
    # preset should silently reintroduce that.
    controller = SonaController()
    for name in controller.preset_names():
        settings = controller.settings(mode=name)
        assert settings.mask_strength <= 1.0, f"{name} extrapolates past the model estimate"


def test_controller_overrides_are_clamped():
    controller = SonaController()
    settings = controller.settings(mode="speech", denoise_strength=2.0, safety_floor=-1.0)
    assert settings.mask_strength == 1.25
    assert settings.safety_floor == 0.0

    bypassed = controller.settings(mode="speech", bypass_eq=True, bypass_compressor=True)
    assert bypassed.bypass_eq is True
    assert bypassed.bypass_compressor is True


def test_preference_memory_roundtrip(tmp_path):
    memory = PreferenceMemory(tmp_path / "prefs.json")
    controller = SonaController(memory=memory)
    settings = controller.settings(mode="music", denoise_strength=0.33, use_memory=False)

    record = memory.set("Traffic", "music", settings)
    assert record.scene == "traffic"
    loaded = memory.get("traffic")
    assert loaded is not None
    assert loaded.mode == "music"
    assert loaded.settings.mask_strength == 0.33

    controller2 = SonaController(memory=PreferenceMemory(tmp_path / "prefs.json"))
    remembered = controller2.settings(scene="traffic")
    assert remembered.mask_strength == 0.33
    assert remembered.eq_gains_db == settings.eq_gains_db


def test_explicit_mode_beats_memory(tmp_path):
    memory = PreferenceMemory(tmp_path / "prefs.json")
    controller = SonaController(memory=memory)
    memory.set("fan", "music", controller.settings(mode="music", use_memory=False))

    remembered = controller.settings(scene="fan")
    explicit = controller.settings(scene="fan", mode="speech")
    assert remembered.mask_strength != explicit.mask_strength
    assert explicit == controller.settings(mode="speech", use_memory=False)


def test_scene_classifier_handles_silence_and_tones():
    sr = 16000
    classifier = SceneClassifier(sr=sr)
    silence = np.zeros(sr, dtype=np.float32)
    pred_silence = classifier.predict(silence, sr=sr)
    assert pred_silence.label == "unknown"

    t = np.arange(sr, dtype=np.float32) / sr
    tone = 0.2 * np.sin(2 * np.pi * 220.0 * t).astype(np.float32)
    pred_tone = classifier.predict(tone, sr=sr)
    assert pred_tone.label in classifier.labels
    assert 0.0 <= pred_tone.confidence <= 1.0
    assert pred_tone.features["rms"] > 0.0


def test_learned_scene_model_loads_and_is_default():
    # the learned decision rule (scene_model.py) is generated by
    # sona-final-month/scripts/train_scene_mlp.py; guard that it is present,
    # wired in by default, and produces a valid label on clean speech.
    classifier = SceneClassifier(sr=16000)
    assert classifier.use_learned, "learned scene model should be active by default"

    rng = np.random.default_rng(0)
    sr = 16000
    t = np.arange(2 * sr, dtype=np.float32) / sr
    # voiced-like: low-frequency carrier + harmonics + slow amplitude modulation
    env = 0.5 + 0.5 * np.sin(2 * np.pi * 3.0 * t).astype(np.float32)
    voiced = env * sum(
        (0.5 / k) * np.sin(2 * np.pi * 150.0 * k * t).astype(np.float32)
        for k in (1, 2, 3, 4)
    )
    voiced += 0.01 * rng.standard_normal(voiced.shape).astype(np.float32)
    pred = classifier.predict(voiced, sr=sr)
    assert pred.label in classifier.labels
    assert 0.0 <= pred.confidence <= 1.0


def test_scene_classifier_heuristic_fallback_still_works():
    # with the learned rule disabled the hand-tuned heuristic must still return
    # a valid prediction (the model file may be absent on a fresh checkout).
    classifier = SceneClassifier(sr=16000, use_learned=False)
    assert not classifier.use_learned
    rng = np.random.default_rng(1)
    noise = 0.1 * rng.standard_normal(16000).astype(np.float32)
    pred = classifier.predict(noise, sr=16000)
    assert pred.label in classifier.labels
    assert 0.0 <= pred.confidence <= 1.0


def test_post_processing_neutral_keeps_shape_and_bounds():
    sr = 16000
    t = np.arange(sr // 2, dtype=np.float32) / sr
    wav = 0.1 * np.sin(2 * np.pi * 440.0 * t).astype(np.float32)
    settings = ControllerSettings(
        mask_strength=1.0,
        safety_floor=0.0,
        eq_gains_db=(0.0,) * 8,
        compressor_threshold_db=0.0,
        compressor_ratio=1.0,
        compressor_makeup_db=0.0,
    )
    out = apply_post_processing(wav, settings, sr=sr, n_fft=256, hop=64, device="cpu")
    assert out.shape == wav.shape
    assert np.isfinite(out).all()
    assert np.max(np.abs(out)) <= 1.0
    assert np.max(np.abs(out - wav)) < 1e-4
